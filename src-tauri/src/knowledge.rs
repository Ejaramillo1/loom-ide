fn err(e: impl std::fmt::Display) -> String {
    e.to_string()
}
fn now() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs()
}
fn id() -> String {
    format!(
        "n-{}-{}",
        SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos(),
        std::process::id()
    )
}
fn json(value: &impl Serialize) -> Result<String, String> {
    serde_json::to_string_pretty(value).map_err(err)
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Meta {
    pub id: String,
    pub kind: String,
    pub title: String,
    pub created: u64,
    pub modified: u64,
    pub author: String,
    pub source: String,
    pub status: String,
    pub version: u32,
}
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Note {
    pub meta: Meta,
    pub body: String,
    pub path: String,
    pub original: String,
}
impl Note {
    fn encode(&self) -> Result<String, String> {
        let text = format!("---\n{}\n---\n{}", json(&self.meta)?, self.body);
        if text.len() > NOTE_CAP {
            return Err("Notes are limited to 1 MB including metadata".into());
        }
        Ok(text)
    }
}
