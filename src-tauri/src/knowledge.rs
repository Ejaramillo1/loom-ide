#[tauri::command]
pub async fn knowledge_sync_from_loom() -> Result<usize, String> {
    tauri::async_runtime::spawn_blocking(|| {
        let mut count = 0;
        for (path, key, kind, folder) in [
            ("/v1/sessions?limit=500", "sessions", "session", FOLDERS[8]),
            ("/v1/agents", "agents", "agent", FOLDERS[9]),
            (
                "/v1/artifacts?limit=200",
                "artifacts",
                "artifact",
                FOLDERS[7],
            ),
        ] {
            let value = crate::loom_request("GET", path, None)
                .map_err(|e| format!("Sync stopped after {count} notes: {e}"))?;
            count += with_vault(|v| v.mirror(&value, key, kind, folder))
                .map_err(|e| format!("Sync stopped after {count} notes: {e}"))?;
        }
        Ok(count)
    })
    .await
    .map_err(err)?
}

